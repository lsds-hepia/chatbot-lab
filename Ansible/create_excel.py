#!/usr/bin/env python3
"""
Script to create Excel file with user numbers and chatbot URLs
Reads from instance_ip.ini file generated by Ansible
"""

import os
import csv

def read_instance_ips():
    """Read IP addresses from instance_ip.ini file"""
    ips = []
    try:
        with open('instance_ip.ini', 'r') as f:
            lines = f.readlines()
            for line in lines:
                line = line.strip()
                if line and not line.startswith('[') and line != 'my_hosts':
                    ips.append(line)
    except FileNotFoundError:
        print("Error: instance_ip.ini file not found")
        return []
    
    return ips

def create_csv_file(ips):
    """Create CSV file with user numbers and URLs"""
    if not ips:
        print("No IP addresses found")
        return
    
    with open('chatbot_access.csv', 'w', newline='') as csvfile:
        writer = csv.writer(csvfile)
        writer.writerow(['User Number', 'Chatbot URL'])
        
        for i, ip in enumerate(ips, 1):
            user_number = f'user{i}'
            url = f'http://{ip}:8501'
            writer.writerow([user_number, url])
    
    print(f"CSV file created: chatbot_access.csv with {len(ips)} entries")

def create_html_file(ips):
    """Create HTML file with user numbers and URLs"""
    if not ips:
        return
    
    html_content = """<!DOCTYPE html>
<html>
<head>
    <title>Chatbot Access URLs</title>
    <style>
        body { font-family: Arial, sans-serif; margin: 40px; }
        h1 { color: #333; }
        table { border-collapse: collapse; width: 100%; }
        th, td { border: 1px solid #ddd; padding: 12px; text-align: left; }
        th { background-color: #f2f2f2; }
        tr:nth-child(even) { background-color: #f9f9f9; }
        a { color: #0066cc; text-decoration: none; }
        a:hover { text-decoration: underline; }
    </style>
</head>
<body>
    <h1>Chatbot Access URLs</h1>
    <p>Click on the URLs below to access each user's chatbot:</p>
    <table>
        <thead>
            <tr>
                <th>User Number</th>
                <th>Chatbot URL</th>
            </tr>
        </thead>
        <tbody>
"""
    
    for i, ip in enumerate(ips, 1):
        user_number = f'user{i}'
        url = f'http://{ip}:8501'
        html_content += f'            <tr><td>{user_number}</td><td><a href="{url}" target="_blank">{url}</a></td></tr>\n'
    
    html_content += """        </tbody>
    </table>
</body>
</html>"""
    
    with open('chatbot_access.html', 'w') as htmlfile:
        htmlfile.write(html_content)
    
    print(f"HTML file created: chatbot_access.html with {len(ips)} entries")

def main():
    print("Creating files from instance IPs...")
    ips = read_instance_ips()
    
    if ips:
        create_csv_file(ips)
        create_html_file(ips)
        print("\nCreated files:")
        print("- chatbot_access.csv (can be opened in Excel)")
        print("- chatbot_access.html (clickable links)")
        
        # Try to create actual Excel file if openpyxl is available
        try:
            import pandas as pd
            df = pd.read_csv('chatbot_access.csv')
            df.to_excel('chatbot_access.xlsx', index=False, sheet_name='Chatbot URLs')
            print("- chatbot_access.xlsx (Excel format)")
        except ImportError:
            print("- Install pandas and openpyxl for .xlsx format: pip install pandas openpyxl")
    else:
        print("No instance IPs found to process")

if __name__ == "__main__":
    main()